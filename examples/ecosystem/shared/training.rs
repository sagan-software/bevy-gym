/// Bounded historical policy snapshots used only as predator opponents.
struct HistoricalOpponents {
    /// Earliest scheduled bunny snapshot after fox acquisition.
    bunny_early: Option<RecurrentPpoPolicy>,

    /// Middle scheduled bunny snapshot.
    bunny_middle: Option<RecurrentPpoPolicy>,

    /// Best validation-selected bunny snapshot so far.
    bunny_best: RecurrentPpoPolicy,

    /// Earliest scheduled fox snapshot after acquisition.
    fox_early: Option<RecurrentPpoPolicy>,

    /// Middle scheduled fox snapshot.
    fox_middle: Option<RecurrentPpoPolicy>,

    /// Best validation-selected fox snapshot so far.
    fox_best: Option<RecurrentPpoPolicy>,
}

impl HistoricalOpponents {
    /// Initialize the bounded pool from step-zero policies.
    fn new(learners: &Learners) -> Self {
        Self {
            bunny_early: None,
            bunny_middle: None,
            bunny_best: learners.bunny.policy(),
            fox_early: None,
            fox_middle: None,
            fox_best: learners.fox.as_ref().map(RecurrentPpoAgent::policy),
        }
    }

    /// Record scheduled progression roles and the best-so-far role.
    fn record(
        &mut self,
        learners: &Learners,
        completed_iteration: usize,
        total_iterations: usize,
        is_best: bool,
    ) {
        if self.bunny_early.is_none() && completed_iteration.saturating_mul(3) >= total_iterations {
            self.bunny_early = Some(learners.bunny.policy());
            self.fox_early = learners.fox.as_ref().map(RecurrentPpoAgent::policy);
        }
        if self.bunny_middle.is_none()
            && completed_iteration.saturating_mul(3) >= total_iterations.saturating_mul(2)
        {
            self.bunny_middle = Some(learners.bunny.policy());
            self.fox_middle = learners.fox.as_ref().map(RecurrentPpoAgent::policy);
        }
        if is_best {
            self.bunny_best = learners.bunny.policy();
            self.fox_best = learners.fox.as_ref().map(RecurrentPpoAgent::policy);
        }
    }

    /// Select one immutable bunny opponent snapshot.
    fn bunny(&self, current: RecurrentPpoPolicy, role: OpponentRole) -> RecurrentPpoPolicy {
        match role {
            OpponentRole::Current => current,
            OpponentRole::Early => self
                .bunny_early
                .as_ref()
                .unwrap_or(&self.bunny_best)
                .clone(),
            OpponentRole::Middle => self
                .bunny_middle
                .as_ref()
                .or(self.bunny_early.as_ref())
                .unwrap_or(&self.bunny_best)
                .clone(),
            OpponentRole::Best => self.bunny_best.clone(),
        }
    }

    /// Select one immutable fox opponent snapshot when foxes exist.
    fn fox(
        &self,
        current: Option<RecurrentPpoPolicy>,
        role: OpponentRole,
    ) -> Option<RecurrentPpoPolicy> {
        match role {
            OpponentRole::Current => current,
            OpponentRole::Early => self.fox_early.as_ref().or(self.fox_best.as_ref()).cloned(),
            OpponentRole::Middle => self
                .fox_middle
                .as_ref()
                .or(self.fox_early.as_ref())
                .or(self.fox_best.as_ref())
                .cloned(),
            OpponentRole::Best => self.fox_best.clone(),
        }
    }
}

impl std::fmt::Debug for CollectionPolicies {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("CollectionPolicies")
            .field("bunny", &self.bunny)
            .field("fox", &self.fox)
            .field("bunny_sampler", &self.bunny_sampler)
            .field("fox_sampler", &self.fox_sampler)
            .finish()
    }
}

