/// Pair carried and zero-memory actions at learner-visited survival observations.
fn survival_memory_invariance_samples(
    learner: &RecurrentPpoAgent,
    config: SimulationConfig,
    seed: u64,
    count: usize,
) -> Result<Vec<RecurrentBehaviorMemorySample>, Box<dyn Error>> {
    let policy = learner.policy();
    let zero_memory = policy.initial_memory();
    let mut samples = Vec::with_capacity(count.saturating_mul(2));
    let mut visited = 0_usize;
    let mut episode = 0_usize;
    while visited < count {
        let episode_seed = seed ^ (episode as u64).rotate_left(17);
        let mut ecosystem = Ecosystem::new_rotated(config.clone(), episode_seed, episode)?;
        let mut memory = zero_memory.clone();
        for _ in 0..SURVIVAL_MEMORY_INVARIANCE_FRAGMENT_LENGTH {
            let state = ecosystem.state();
            let (id, species, observation) = state
                .agents
                .first()
                .ok_or("memory-invariance world has no actor")?;
            if species != &Species::Bunny {
                return Err("memory-invariance world must contain one bunny".into());
            }
            let target = policy.mean_action(observation, &zero_memory)?.action;
            samples.push(RecurrentBehaviorMemorySample {
                observation: observation.to_vec(),
                initial_memory: memory.clone(),
                action: target.clone(),
            });
            samples.push(RecurrentBehaviorMemorySample {
                observation: observation.to_vec(),
                initial_memory: zero_memory.clone(),
                action: target,
            });
            visited = visited.saturating_add(1);
            if visited == count {
                break;
            }

            let learner_action = policy.mean_action(observation, &memory)?;
            let [forward, turn, gaze, attack] = learner_action.action.as_slice() else {
                return Err("memory-invariance policy must emit exactly four action axes".into());
            };
            let locomotion = LocomotionAction::new(*forward, *turn, *gaze, *attack)?;
            let result = ecosystem.step(&[(*id, locomotion)])?;
            memory = learner_action.next_memory;
            let agent = result
                .agents
                .first()
                .ok_or("memory-invariance step must return one agent")?;
            if agent.status != EpisodeStatus::Continuing {
                break;
            }
        }
        episode = episode.saturating_add(1);
    }
    Ok(samples)
}

/// Combine paired survival corrections with twice as many frozen forage targets.
fn survival_memory_invariance_batch(
    learner: &RecurrentPpoAgent,
    config: SimulationConfig,
    seed: u64,
    count: usize,
    forage_anchors: &[RecurrentBehaviorMemorySample],
) -> Result<Vec<RecurrentBehaviorMemorySample>, Box<dyn Error>> {
    if forage_anchors.len() != count.saturating_mul(4) {
        return Err("forage anchors must outnumber paired survival corrections two to one".into());
    }
    let mut samples = survival_memory_invariance_samples(learner, config, seed, count)?;
    samples.extend_from_slice(forage_anchors);
    Ok(samples)
}

