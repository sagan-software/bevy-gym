/// Generate deterministic food-and-water demonstrations from live survival states.
fn survival_expert_samples(
    config: SimulationConfig,
    seed: u64,
    count: usize,
) -> Result<SurvivalExpertBatch, Box<dyn Error>> {
    let mut samples = Vec::with_capacity(count);
    let mut food_recoveries = 0_usize;
    let mut water_recoveries = 0_usize;
    let hidden_sample_limit = count / SURVIVAL_EXPERT_HIDDEN_DIVISOR;
    let mut hidden_samples = 0_usize;
    let mut episode_index = 0_usize;
    let mut teacher_step = 0_usize;
    while samples.len() < count {
        let episode_seed = seed ^ (episode_index as u64).rotate_left(17);
        let mut ecosystem = Ecosystem::new_rotated(config.clone(), episode_seed, episode_index)?;
        loop {
            let state = ecosystem.state();
            let (id, species, observation) = state
                .agents
                .first()
                .ok_or("survival expert world has no actor")?;
            if species != &Species::Bunny {
                return Err("survival expert world must contain one bunny".into());
            }
            let action = survival_expert_action(observation);
            let target_visible =
                nearest_observed_ray(observation, survival_target_kind(observation)).is_some();
            let sample = RecurrentBehaviorSample {
                observation: observation.to_vec(),
                action: action.to_vec(),
            };
            if teacher_step.is_multiple_of(SURVIVAL_EXPERT_SAMPLE_STRIDE) {
                if target_visible {
                    let mirrored = mirror_survival_sample(&sample)?;
                    samples.push(sample);
                    if samples.len() < count {
                        samples.push(mirrored);
                    }
                } else if hidden_samples < hidden_sample_limit {
                    samples.push(sample);
                    hidden_samples = hidden_samples.saturating_add(1);
                }
            }
            if samples.len() == count {
                break;
            }
            let locomotion = LocomotionAction::new(action[0], action[1], action[2], action[3])?;
            let step = ecosystem.step(&[(*id, locomotion)])?;
            let Some(agent) = step.agents.first() else {
                return Err("survival expert step returned no actor".into());
            };
            teacher_step = teacher_step.saturating_add(1);
            food_recoveries =
                food_recoveries.saturating_add(usize::from(agent.observation[0] > observation[0]));
            water_recoveries =
                water_recoveries.saturating_add(usize::from(agent.observation[1] > observation[1]));
            let continues = agent.status == EpisodeStatus::Continuing;
            if !continues {
                break;
            }
        }
        episode_index = episode_index.saturating_add(1);
    }
    Ok(SurvivalExpertBatch {
        samples,
        food_recoveries,
        water_recoveries,
    })
}

/// Choose the currently larger visible need and search when its resource is hidden.
fn survival_expert_action(observation: &LocalObservation) -> [f32; 4] {
    // Avoid immediate solids before selecting or searching for a resource.
    if let Some(action) = survival_obstacle_avoidance(observation) {
        return action;
    }
    let target = survival_target_kind(observation);
    let Some(bearing) = observed_ray_bearing(observation, target) else {
        return survival_search_action(observation);
    };
    let forward = if bearing.abs() < 0.20 { 1.0 } else { -1.0 };
    let turn = (bearing / 0.9).clamp(-1.0, 1.0);
    let target_need = if target == PerceptKind::Food {
        observation[0]
    } else {
        observation[1]
    };
    let attack = if target_need < 1.0 { 1.0 } else { 0.0 };
    [forward, turn, 0.0, attack]
}

/// Sweep broad alternating arcs so an occluded resource requires exploration.
fn survival_search_action(observation: &LocalObservation) -> [f32; 4] {
    // Alternate slow arcs by episode age so search does not remain one circle.
    let search_phase = (observation[3].clamp(0.0, 1.0) * 12.0).floor();
    let direction = if search_phase.rem_euclid(2.0) < 1.0 {
        1.0
    } else {
        -1.0
    };
    [1.0, direction * 0.12, direction, 1.0]
}

/// Turn away from the nearest close solid ray before resuming resource pursuit.
fn survival_obstacle_avoidance(observation: &LocalObservation) -> Option<[f32; 4]> {
    let ray_width = RAY_FEATURE_SIZE;
    // React to the nearest solid inside the braking distance of 12% sight range.
    let nearest = (0..RAY_COUNT)
        .filter_map(|ray_index| {
            let start = PROPRIOCEPTION_SIZE + ray_index * ray_width;
            let ray = observation.get(start..start + ray_width)?;
            let is_solid = ray
                .get(RAY_KIND_START + PerceptKind::SolidObstacle.index())
                .copied()?
                > 0.5
                || ray
                    .get(RAY_KIND_START + PerceptKind::Boundary.index())
                    .copied()?
                    > 0.5;
            let distance = *ray.first()?;
            (is_solid && distance < 0.12).then_some((ray_index, distance))
        })
        .min_by(|(_, left), (_, right)| left.total_cmp(right));
    let (ray_index, _) = nearest?;
    let bearing = RAY_ANGLES.get(ray_index).copied().unwrap_or_default();
    let turn = if bearing >= 0.0 { -1.0 } else { 1.0 };
    Some([-1.0, turn, 0.0, 1.0])
}

/// Select the resource associated with the larger physiological need.
fn survival_target_kind(observation: &LocalObservation) -> PerceptKind {
    if observation[1] < observation[0] {
        PerceptKind::Well
    } else {
        PerceptKind::Food
    }
}

/// Mirror every egocentric lateral channel and its paired action exactly.
fn mirror_survival_sample(
    sample: &RecurrentBehaviorSample,
) -> Result<RecurrentBehaviorSample, Box<dyn Error>> {
    let mut observation = sample.observation.clone();
    for index in [LOCAL_LATERAL_VELOCITY_INDEX, 6, LOCAL_GAZE_YAW_INDEX] {
        let value = observation
            .get_mut(index)
            .ok_or("survival mirror proprioception index is outside the actor tensor")?;
        *value = -*value;
    }
    // Ray angles are stored as adjacent positive-negative pairs.
    let ray_width = RAY_FEATURE_SIZE;
    let ray_end = PROPRIOCEPTION_SIZE + RAY_COUNT * ray_width;
    let rays = observation
        .get_mut(PROPRIOCEPTION_SIZE..ray_end)
        .ok_or("survival mirror rays are outside the actor tensor")?;
    for pair in rays.chunks_exact_mut(ray_width * 2) {
        let (positive, negative) = pair.split_at_mut(ray_width);
        for (positive_channel, negative_channel) in positive.iter_mut().zip(negative.iter_mut()) {
            std::mem::swap(positive_channel, negative_channel);
        }
    }

    let [forward, turn, gaze, attack] = sample.action.as_slice() else {
        return Err("survival expert action must contain four axes".into());
    };
    Ok(RecurrentBehaviorSample {
        observation,
        action: vec![*forward, -*turn, -*gaze, *attack],
    })
}

/// Policy update mode for one curriculum iteration.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum TrainingPhase {
    /// Update every policy represented by the stage.
    Joint,
    /// Hold bunnies stationary while the fox first acquires pursuit behavior.
    FoxAcquisition,
    /// Update only the bunny policy against the current fox policy.
    Bunny,
    /// Update only the fox policy against the current bunny policy.
    Fox,
}

/// Environment-lane execution policy for one curriculum stage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CollectionStrategy {
    /// Collect one complete lane before starting the next lane.
    Sequential,

    /// Collect independent lanes concurrently on scoped worker threads.
    Parallel,
}

impl CollectionStrategy {
    /// Keep parallel batching scoped to survival until later stages opt in.
    const fn for_stage(stage: CurriculumStage) -> Self {
        if matches!(stage, CurriculumStage::Survival) {
            Self::Parallel
        } else {
            Self::Sequential
        }
    }
}

/// Execution strategy for fixed-seed policy evaluation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum EvaluationStrategy {
    /// Evaluate one complete episode before starting the next episode.
    Sequential,

    /// Evaluate independent episodes concurrently under frozen policy weights.
    Parallel,
}

impl EvaluationStrategy {
    /// Keep the performance change scoped to the requested survival stage.
    const fn for_stage(stage: CurriculumStage) -> Self {
        if matches!(stage, CurriculumStage::Survival) {
            Self::Parallel
        } else {
            Self::Sequential
        }
    }
}

/// One bounded historical-opponent role.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum OpponentRole {
    /// Current opposing policy.
    Current,
    /// Snapshot near one-third of training.
    Early,
    /// Snapshot near two-thirds of training.
    Middle,
    /// Best validation-selected snapshot so far.
    Best,
}

/// Return whether training starts after the predator acquisition phase.
const fn initial_fox_acquired(stage: CurriculumStage, resume_is_current_stage: bool) -> bool {
    !matches!(stage, CurriculumStage::PredatorPrey) || resume_is_current_stage
}

impl TrainingPhase {
    /// Whether this phase updates the bunny policy.
    const fn updates_bunny(self) -> bool {
        matches!(self, Self::Joint | Self::Bunny)
    }

    /// Whether this phase updates the fox policy.
    const fn updates_fox(self) -> bool {
        matches!(self, Self::Joint | Self::FoxAcquisition | Self::Fox)
    }

    /// Whether prey actions remain stationary during fox acquisition.
    const fn freezes_bunnies(self) -> bool {
        matches!(self, Self::FoxAcquisition)
    }
}

/// Return whether a requested species update has at least one intact sequence.
const fn policy_update_available(requested: bool, sequence_count: usize) -> bool {
    requested && sequence_count > 0
}

/// Select fox acquisition first, then alternate adversarial policy updates.
const fn training_phase(
    stage: CurriculumStage,
    iteration: usize,
    fox_acquired: bool,
) -> TrainingPhase {
    if !matches!(stage, CurriculumStage::PredatorPrey) {
        return TrainingPhase::Joint;
    }
    if !fox_acquired {
        return TrainingPhase::FoxAcquisition;
    }
    if iteration.is_multiple_of(2) {
        TrainingPhase::Bunny
    } else {
        TrainingPhase::Fox
    }
}

/// Cycle each alternating species through every bounded opponent role.
const fn opponent_role(phase: TrainingPhase, iteration: usize) -> OpponentRole {
    let alternating_index = match phase {
        TrainingPhase::Bunny => iteration.saturating_sub(4) / 2,
        TrainingPhase::Fox => iteration.saturating_sub(5) / 2,
        TrainingPhase::Joint | TrainingPhase::FoxAcquisition => 0,
    };
    match alternating_index % 4 {
        0 => OpponentRole::Current,
        1 => OpponentRole::Early,
        2 => OpponentRole::Middle,
        _ => OpponentRole::Best,
    }
}

/// Collect independent worlds under one unchanged behavior policy snapshot.
fn collect_batch(
    learners: &Learners,
    config: SimulationConfig,
    seeds: SeedConfig,
    iteration: usize,
    rollout_episodes: usize,
    algorithm: &RecurrentPpoConfig,
    forage_nursery_beta: f32,
    phase: TrainingPhase,
    opponents: &HistoricalOpponents,
    competition_scarce: bool,
    capture_visual: bool,
) -> Result<CollectedBatch, Box<dyn Error>> {
    let target_stage = config.stage;
    let tuning = config.experiment_tuning();
    let episode_seconds = config.episode_seconds;
    let mut tasks = Vec::with_capacity(rollout_episodes);
    for lane in 0..rollout_episodes {
        let episode_index = iteration
            .saturating_mul(rollout_episodes)
            .saturating_add(lane);
        let seed = seeds.environment_episode(lane, episode_index as u64);
        let policies = collection_policies(
            learners,
            seeds,
            episode_index as u64,
            iteration,
            phase,
            opponents,
        );
        let rollout_stage = curriculum_rollout_stage(target_stage, lane);
        let mut rollout_config = SimulationConfig::for_stage(rollout_stage)?;
        rollout_config.apply_experiment_tuning(tuning)?;
        if rollout_stage == CurriculumStage::Forage {
            rollout_config.forage_difficulty =
                forage_rollout_difficulty(config.forage_difficulty, lane);
        }
        if target_stage == CurriculumStage::Competition
            && rollout_stage == CurriculumStage::Competition
        {
            apply_competition_resource_curriculum(&mut rollout_config, competition_scarce, lane);
        }
        rollout_config.episode_seconds = episode_seconds;
        tasks.push(CollectionLaneTask {
            lane,
            config: rollout_config,
            seed,
            episode_index,
            policies,
            phase,
            forage_nursery_beta,
            gamma: algorithm.gamma,
            capture_visual: capture_visual && lane < SURVIVAL_BATCH_ENVIRONMENTS,
        });
    }

    // Join in lane order so seeded batches and metric arrays stay reproducible.
    let lanes = match CollectionStrategy::for_stage(target_stage) {
        CollectionStrategy::Sequential => tasks
            .into_iter()
            .map(collect_lane)
            .collect::<Result<Vec<_>, _>>()?,
        CollectionStrategy::Parallel => collect_lanes_in_parallel(tasks)?,
    };
    #[cfg(feature = "render")]
    let mut lanes = lanes;
    #[cfg(feature = "render")]
    let visual_trace = if capture_visual {
        Some(build_survival_batch_trace(
            iteration.saturating_add(1),
            &mut lanes,
        )?)
    } else {
        None
    };
    let mut batch = CollectedBatch::default();
    for lane in lanes {
        debug_assert_eq!(lane.lane, batch.bunny_returns.len());
        batch.push_lane(lane, algorithm);
    }
    #[cfg(feature = "render")]
    {
        batch.visual_trace = visual_trace;
    }
    Ok(batch)
}

/// Collect one prepared environment lane without sharing mutable state.
fn collect_lane(task: CollectionLaneTask) -> Result<CollectedLane, Box<dyn Error>> {
    let episode = collect_episode(
        task.config.clone(),
        task.seed,
        task.episode_index,
        task.policies,
        task.phase,
        task.forage_nursery_beta,
        task.gamma,
        task.capture_visual,
    )?;
    Ok(CollectedLane {
        lane: task.lane,
        config: task.config,
        episode,
    })
}

/// Run independent survival lanes concurrently and preserve their input order.
fn collect_lanes_in_parallel(
    tasks: Vec<CollectionLaneTask>,
) -> Result<Vec<CollectedLane>, Box<dyn Error>> {
    std::thread::scope(|scope| {
        let handles = tasks
            .into_iter()
            .map(|task| scope.spawn(move || collect_lane(task).map_err(|error| error.to_string())))
            .collect::<Vec<_>>();
        let mut lanes = Vec::with_capacity(handles.len());
        for handle in handles {
            let joined = handle.join();
            match joined {
                Ok(Ok(lane)) => lanes.push(lane),
                Ok(Err(message)) => return Err(io::Error::other(message).into()),
                Err(_) => {
                    return Err(io::Error::other("survival collection lane panicked").into());
                }
            }
        }
        Ok(lanes)
    })
}

/// Convert the first nine contributing lanes into one validated visual trace.
#[cfg(feature = "render")]
fn build_survival_batch_trace(
    iteration: usize,
    lanes: &mut [CollectedLane],
) -> Result<SurvivalBatchTrace, Box<dyn Error>> {
    let time_step = lanes
        .first()
        .map(|lane| lane.config.time_step)
        .ok_or("survival batch did not collect any lanes")?;
    let traces = lanes
        .iter_mut()
        .take(SURVIVAL_BATCH_ENVIRONMENTS)
        .map(|lane| {
            SurvivalLaneTrace::new(
                lane.lane,
                lane.config.stage,
                std::mem::take(&mut lane.episode.visual_snapshots),
                std::mem::take(&mut lane.episode.visual_returns),
            )
        })
        .collect::<io::Result<Vec<_>>>()?;
    Ok(SurvivalBatchTrace::new(iteration, time_step, traces)?)
}

/// Collect one simultaneous multi-agent episode under frozen policies.
fn collect_episode(
    config: SimulationConfig,
    seed: u64,
    spawn_rotation: usize,
    mut policies: CollectionPolicies,
    phase: TrainingPhase,
    forage_nursery_beta: f32,
    gamma: f32,
    capture_visual: bool,
) -> Result<CollectedEpisode, Box<dyn Error>> {
    let mut ecosystem = Ecosystem::new_rotated(config, seed, spawn_rotation)?;
    let mut current = ecosystem.state();
    let mut memories = BTreeMap::<AgentId, RecurrentMemory>::new();
    let mut episode = CollectedEpisode::default();

    #[cfg(feature = "render")]
    if capture_visual {
        episode.visual_snapshots.push(ecosystem.visual_snapshot());
        episode.visual_returns.push(0.0);
    }
    #[cfg(not(feature = "render"))]
    let _ = capture_visual;

    loop {
        let mut actions = Vec::with_capacity(current.agents.len());
        let mut selected = BTreeMap::new();
        for (id, species, observation) in &current.agents {
            let (policy, sampler) = policy_and_sampler(&mut policies, *species)?;
            let memory = memories
                .entry(*id)
                .or_insert_with(|| policy.initial_memory())
                .clone();
            let action = policy.sample_action(observation, &memory, sampler)?;
            let value = policy.value(&current.global_state, usize::from(id.0))?;
            let [forward, turn, gaze, attack] = action.action.as_slice() else {
                return Err("ecosystem policy must emit exactly four action axes".into());
            };
            let locomotion = if species == &Species::Bunny && phase.freezes_bunnies() {
                LocomotionAction::new(-1.0, 0.0, 0.0, -1.0)?
            } else {
                LocomotionAction::new(*forward, *turn, *gaze, *attack)?
            };
            actions.push((*id, locomotion));
            selected.insert(*id, (*species, observation, memory, action, value));
        }

        let result = ecosystem.step(&actions)?;
        episode.joint_steps = episode.joint_steps.saturating_add(1);
        #[cfg(feature = "render")]
        let mut visual_step_return = 0.0_f64;
        let mut next_agents = Vec::new();
        for agent_step in &result.agents {
            let Some((species, observation, initial_memory, action, value)) =
                selected.remove(&agent_step.id)
            else {
                return Err("joint step returned an agent absent from its action set".into());
            };
            let policy = policy_for_species(&policies, species)?;
            let next_value = if should_bootstrap_collected_transition(agent_step.status) {
                policy.value(&result.global_state, usize::from(agent_step.id.0))?
            } else {
                0.0
            };
            let consumed_food = agent_step.observation[0] > observation[0];
            let task_reward = if species == Species::Bunny {
                forage_nursery_reward(
                    agent_step.reward as f32,
                    observation,
                    &agent_step.observation,
                    agent_step.status,
                    consumed_food,
                    gamma,
                    forage_nursery_beta,
                )
            } else {
                agent_step.reward as f32
            };
            #[cfg(feature = "render")]
            if species == Species::Bunny {
                visual_step_return += f64::from(task_reward);
            }
            episode
                .trajectories
                .entry(agent_step.id)
                .or_insert_with(|| (species, Vec::new()))
                .1
                .push(RolloutTransition {
                    observation: *observation,
                    global_state: current.global_state,
                    pre_tanh_action: action.pre_tanh_action,
                    old_log_probability: action.log_probability,
                    reward: task_reward,
                    value,
                    next_value,
                    status: agent_step.status,
                    initial_memory,
                });
            if agent_step.status == EpisodeStatus::Continuing {
                memories.insert(agent_step.id, action.next_memory);
                next_agents.push((agent_step.id, species, agent_step.observation));
            } else {
                memories.remove(&agent_step.id);
            }
        }
        #[cfg(feature = "render")]
        if capture_visual {
            let previous_return = episode.visual_returns.last().copied().unwrap_or_default();
            episode.visual_snapshots.push(ecosystem.visual_snapshot());
            episode
                .visual_returns
                .push(previous_return + visual_step_return);
        }
        if result.is_done {
            break;
        }
        current.agents = next_agents;
        current.global_state = result.global_state;
    }
    Ok(episode)
}

/// Bootstrap only transitions whose episode continues after the current step.
fn should_bootstrap_collected_transition(status: EpisodeStatus) -> bool {
    status == EpisodeStatus::Continuing
}

/// Resolve the actor and mutable action stream for one biological role.
fn policy_and_sampler(
    policies: &mut CollectionPolicies,
    species: Species,
) -> Result<(&RecurrentPpoPolicy, &mut RecurrentSampler), Box<dyn Error>> {
    match species {
        Species::Bunny => Ok((&policies.bunny, &mut policies.bunny_sampler)),
        Species::Fox => policies
            .fox
            .as_ref()
            .map(|policy| (policy, &mut policies.fox_sampler))
            .ok_or_else(|| "fox agent exists without a fox policy".into()),
    }
}

/// Resolve the immutable species policy for value bootstrapping.
fn policy_for_species(
    policies: &CollectionPolicies,
    species: Species,
) -> Result<&RecurrentPpoPolicy, Box<dyn Error>> {
    match species {
        Species::Bunny => Ok(&policies.bunny),
        Species::Fox => policies
            .fox
            .as_ref()
            .ok_or_else(|| "fox agent exists without a fox policy".into()),
    }
}

/// Compute per-agent GAE, then split only at contiguous chunk boundaries.
fn build_sequences(
    trajectories: &BTreeMap<AgentId, (Species, Vec<RolloutTransition>)>,
    species: Species,
    gamma: f32,
    gae_lambda: f32,
) -> Vec<RecurrentPpoSequence> {
    trajectories
        .iter()
        .filter(|(_, (trajectory_species, _))| *trajectory_species == species)
        .flat_map(|(id, (_, transitions))| {
            let advantages = generalized_advantages(transitions, gamma, gae_lambda);
            transitions
                .chunks(RECURRENT_CHUNK_LENGTH)
                .zip(advantages.chunks(RECURRENT_CHUNK_LENGTH))
                .filter_map(move |(chunk, chunk_advantages)| {
                    let initial_memory = chunk.first()?.initial_memory.clone();
                    Some(RecurrentPpoSequence {
                        observations: chunk
                            .iter()
                            .map(|transition| transition.observation.to_vec())
                            .collect(),
                        global_states: chunk
                            .iter()
                            .map(|transition| transition.global_state.to_vec())
                            .collect(),
                        pre_tanh_actions: chunk
                            .iter()
                            .map(|transition| transition.pre_tanh_action.clone())
                            .collect(),
                        old_log_probabilities: chunk
                            .iter()
                            .map(|transition| transition.old_log_probability)
                            .collect(),
                        advantages: chunk_advantages.to_vec(),
                        returns: chunk
                            .iter()
                            .zip(chunk_advantages)
                            .map(|(transition, advantage)| transition.value + advantage)
                            .collect(),
                        value_index: usize::from(id.0),
                        initial_memory,
                    })
                })
                .collect::<Vec<_>>()
        })
        .collect()
}

/// Compute masked GAE without leaking a reset state across an episode boundary.
fn generalized_advantages(
    transitions: &[RolloutTransition],
    gamma: f32,
    gae_lambda: f32,
) -> Vec<f32> {
    let mut reversed = Vec::with_capacity(transitions.len());
    let mut next_advantage = 0.0;
    for transition in transitions.iter().rev() {
        let bootstrap = transition.status.bootstrap_mask() as f32;
        let trace = f32::from(transition.status == EpisodeStatus::Continuing);
        let delta = (gamma * bootstrap)
            .mul_add(transition.next_value, transition.reward - transition.value);
        let advantage = (gamma * gae_lambda * trace).mul_add(next_advantage, delta);
        reversed.push(advantage);
        next_advantage = advantage;
    }
    reversed.reverse();
    reversed
}

/// Return mean per-agent lifetime for one species.
fn mean_lifetime(episode: &CollectedEpisode, species: Species, time_step: f32) -> f32 {
    let lifetimes: Vec<_> = episode
        .trajectories
        .values()
        .filter(|(trajectory_species, _)| *trajectory_species == species)
        .map(|(_, transitions)| transitions.len() as f32 * time_step)
        .collect();
    if lifetimes.is_empty() {
        0.0
    } else {
        lifetimes.iter().sum::<f32>() / lifetimes.len() as f32
    }
}

/// Return mean undiscounted per-agent episode reward for one species.
fn mean_episode_return(episode: &CollectedEpisode, species: Species) -> f32 {
    let returns = episode
        .trajectories
        .values()
        .filter(|(trajectory_species, _)| *trajectory_species == species)
        .map(|(_, transitions)| {
            transitions
                .iter()
                .map(|transition| transition.reward)
                .sum::<f32>()
        })
        .collect::<Vec<_>>();
    mean(&returns)
}

/// Return a deterministic 1,000-resample percentile interval for a mean.
fn bootstrap_mean_interval(values: &[f32], seed: u64) -> (f32, f32) {
    if values.is_empty() {
        return (0.0, 0.0);
    }
    let mut rng = SplitMix64::new(seed);
    let mut means = Vec::with_capacity(1_000);
    for _ in 0..1_000 {
        let mut total = 0.0;
        for _ in values {
            let index = (rng.next_u64() % values.len() as u64) as usize;
            if let Some(value) = values.get(index) {
                total += value;
            }
        }
        means.push(total / values.len() as f32);
    }
    means.sort_by(f32::total_cmp);
    let fallback = mean(values);
    (
        means.get(25).copied().unwrap_or(fallback),
        means.get(974).copied().unwrap_or(fallback),
    )
}

/// Divide a success count by its population without producing NaN.
fn fraction(successes: u32, count: u32) -> f32 {
    if count == 0 {
        0.0
    } else {
        successes as f32 / count as f32
    }
}

/// Divide a transition count by its eligible population without producing NaN.
fn fraction_u64(successes: u64, count: u64) -> f32 {
    if count == 0 {
        0.0
    } else {
        successes as f32 / count as f32
    }
}

