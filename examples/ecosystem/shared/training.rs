/// Return whether deterministic forage supervision applies to this lesson.
fn forage_teacher_applies(stage: CurriculumStage, resume_is_current_stage: bool) -> bool {
    stage == CurriculumStage::Forage && !resume_is_current_stage
}

/// Return whether deterministic survival supervision applies to this lesson.
fn survival_teacher_applies(stage: CurriculumStage, resume_is_current_stage: bool) -> bool {
    stage == CurriculumStage::Survival && !resume_is_current_stage
}

/// Replace the active bunny only when the isolated survival candidate improves.
fn commit_survival_teacher_candidate(
    learners: &mut Learners,
    candidate: RecurrentPpoAgent,
    evaluation: EvaluationSummary,
    prior_best: EvaluationSummary,
    retention_passed: bool,
) -> bool {
    let is_best = retention_passed
        && evaluation.checkpoint_is_better_than(prior_best, CurriculumStage::Survival, false);
    if is_best {
        learners.bunny = candidate;
    }
    is_best
}

/// Evaluate a survival candidate against its fixed predecessor forage floor.
fn evaluate_survival_retention(
    gate: Option<&SurvivalRetentionGate>,
    learners: &Learners,
) -> Result<Option<SurvivalRetentionEvaluation>, Box<dyn Error>> {
    let Some(gate) = gate else {
        return Ok(None);
    };
    let summary = evaluate_learners(
        learners,
        gate.config.clone(),
        gate.validation_seed,
        gate.episodes,
    )?;
    Ok(Some(SurvivalRetentionEvaluation {
        food_fraction: summary.bunny_food_fraction,
        minimum_food_fraction: gate.minimum_food_fraction,
        passed: summary.bunny_food_fraction >= gate.minimum_food_fraction,
    }))
}

/// Record the predecessor-behavior evidence used by checkpoint selection.
fn write_survival_retention_metric(
    metrics: &mut MetricsWriter,
    global_step: u64,
    evaluation: Option<SurvivalRetentionEvaluation>,
    tuning: ExperimentTuning,
) -> Result<(), Box<dyn Error>> {
    let Some(evaluation) = evaluation else {
        return Ok(());
    };
    let record = MetricRecord::new(global_step)
        .with_field(
            "eval/retained_forage_food_fraction",
            MetricValue::Number(f64::from(evaluation.food_fraction)),
        )
        .with_field(
            "eval/minimum_retained_forage_food_fraction",
            MetricValue::Number(f64::from(evaluation.minimum_food_fraction)),
        )
        .with_field(
            "eval/retention_passed",
            MetricValue::Bool(evaluation.passed),
        );
    metrics.write_record(&with_experiment_metrics(record, tuning))?;
    Ok(())
}

/// Execute the shared trainer with an optional visual progress boundary.
#[expect(
    clippy::too_many_lines,
    reason = "the coordinator keeps batch, evaluation, checkpoint, and UI publication order explicit"
)]
fn run_training_inner(
    stage: CurriculumStage,
    arguments: impl Iterator<Item = String>,
    #[cfg(feature = "render")] mut tuning_provider: Option<&mut dyn FnMut() -> ExperimentTuning>,
    #[cfg(feature = "render")] mut activity_reporter: Option<
        &mut dyn FnMut(TrainerActivity) -> bool,
    >,
    #[cfg(feature = "render")] mut reporter: Option<&mut dyn FnMut(TrainingProgress) -> bool>,
    #[cfg(feature = "render")] mut batch_reporter: Option<
        &mut dyn FnMut(SurvivalBatchTrace) -> bool,
    >,
) -> Result<(), Box<dyn Error>> {
    #[cfg(feature = "render")]
    let initial_tuning = tuning_provider.as_mut().map(|provider| provider());
    #[cfg(not(feature = "render"))]
    let initial_tuning = None;
    let TrainingSetup {
        options,
        seeds,
        algorithm,
        config: prepared_config,
        mut learners,
        paths,
        mut metrics,
    } = prepare_training(stage, arguments, initial_tuning)?;
    let mut config = prepared_config;
    // Open the visual world before evaluation to keep startup responsive.
    #[cfg(feature = "render")]
    if !report_training_start(
        &mut reporter,
        &learners,
        &config,
        &paths,
        &options,
        &algorithm,
    ) {
        return Ok(());
    }
    #[cfg(feature = "render")]
    if !report_activity(
        &mut activity_reporter,
        TrainerActivity::InitializationPreview,
    ) {
        return Ok(());
    }
    #[cfg(feature = "render")]
    if !report_survival_initialization_preview(
        stage,
        &mut batch_reporter,
        &learners,
        &config,
        seeds,
        &algorithm,
    )? {
        return Ok(());
    }
    #[cfg(feature = "render")]
    if !report_activity(
        &mut activity_reporter,
        TrainerActivity::Evaluation {
            iteration: 0,
            episodes: training_validation_episode_count(stage, options.eval_episodes),
        },
    ) {
        return Ok(());
    }
    let has_foxes = config.fox_count > 0;
    let initial_evaluation = initialize_baseline(
        stage,
        &learners,
        &config,
        seeds,
        &options,
        &paths,
        &mut metrics,
    )?;
    let mut best_evaluation = initial_evaluation;
    #[cfg(feature = "render")]
    let mut profile_baseline = initial_evaluation;
    #[cfg(not(feature = "render"))]
    let mut profile_baseline = initial_evaluation;
    let mut output = io::BufWriter::new(io::stdout().lock());
    write_initial_output(&mut output, stage, initial_evaluation, &algorithm)?;
    // Publish the random initialization before the first optimizer update so
    // the visual demo can show a truthful learning baseline.
    #[cfg(feature = "render")]
    if !report_initial_evaluation(
        &mut reporter,
        &learners,
        &config,
        &paths,
        &options,
        &algorithm,
        initial_evaluation,
    ) {
        write_summary(&paths, stage, 0, initial_evaluation, best_evaluation)?;
        writeln!(output, "run_dir={}", paths.run_dir.display())?;
        return Ok(());
    }
    let resume_is_current_stage = resume_uses_current_stage(stage, options.resume.as_deref())?;
    let survival_retention = prepare_survival_retention_gate(
        stage,
        resume_is_current_stage,
        &options,
        &algorithm,
        seeds,
    )?;
    let forage_teacher_evaluation = initialize_forage_teacher(
        stage,
        resume_is_current_stage,
        &mut learners,
        &config,
        seeds,
        &options,
        &paths,
        &mut metrics,
        best_evaluation,
    )?;
    if let Some(teacher_evaluation) = forage_teacher_evaluation {
        if teacher_evaluation.checkpoint_is_better_than(best_evaluation, stage, has_foxes) {
            best_evaluation = teacher_evaluation;
        }
    }
    #[cfg(feature = "render")]
    if stage == CurriculumStage::Survival
        && !report_activity(&mut activity_reporter, TrainerActivity::SurvivalTeacher)
    {
        return Ok(());
    }
    if let Some(teacher_evaluation) = initialize_survival_teacher(
        stage,
        resume_is_current_stage,
        &mut learners,
        &config,
        seeds,
        &options,
        &paths,
        &mut metrics,
        best_evaluation,
        survival_retention.as_ref(),
    )? {
        if teacher_evaluation.checkpoint_is_better_than(best_evaluation, stage, has_foxes) {
            best_evaluation = teacher_evaluation;
        }
    }
    #[cfg(feature = "render")]
    if stage == CurriculumStage::Survival
        && !report_activity(&mut activity_reporter, TrainerActivity::MemoryInvariance)
    {
        return Ok(());
    }
    if let Some(invariant_evaluation) = initialize_survival_memory_invariance(
        stage,
        resume_is_current_stage,
        &mut learners,
        &config,
        seeds,
        &options,
        &paths,
        &mut metrics,
        best_evaluation,
        survival_retention.as_ref(),
    )? {
        if invariant_evaluation.checkpoint_is_better_than(best_evaluation, stage, has_foxes) {
            best_evaluation = invariant_evaluation;
        }
    }
    let mut global_steps = 0_u64;
    let mut historical_opponents = HistoricalOpponents::new(&learners);
    let mut forage_promotion = ForagePromotion::default();
    if let Some(teacher_evaluation) = forage_teacher_evaluation {
        let _ = forage_promotion.record(teacher_evaluation);
    }
    let mut fox_acquired = initial_fox_acquired(stage, resume_is_current_stage);
    let competition_starts_scarce =
        stage == CurriculumStage::Competition && resume_is_current_stage;
    let critic_warmup_iterations = if stage == CurriculumStage::Competition {
        competition_critic_warmup_iterations(options.resume.is_some(), resume_is_current_stage)
    } else {
        0
    };
    let mut competition_promotion = CompetitionPromotion::new(competition_starts_scarce);
    for iteration in 0..options.iterations {
        // Apply UI changes only between complete rollout batches so every PPO
        // update retains one stationary reward and dynamics definition.
        #[cfg(feature = "render")]
        if let Some(provider) = tuning_provider.as_mut() {
            if let Some(baseline) = apply_training_tuning(
                provider,
                &mut config,
                TuningPersistence {
                    learners: &learners,
                    paths: &paths,
                    options: &options,
                    algorithm: &algorithm,
                    seeds,
                    stage,
                },
            )? {
                best_evaluation = baseline;
                profile_baseline = baseline;
            }
        }
        let phase = training_phase(stage, iteration, fox_acquired);
        let nursery_beta = if stage == CurriculumStage::Forage {
            forage_nursery_beta(config.forage_difficulty, iteration, options.iterations)
        } else {
            0.0
        };
        #[cfg(feature = "render")]
        let capture_visual_batch = stage == CurriculumStage::Survival && batch_reporter.is_some();
        #[cfg(not(feature = "render"))]
        let capture_visual_batch = false;
        #[cfg(feature = "render")]
        if !report_activity(
            &mut activity_reporter,
            TrainerActivity::Collection {
                iteration: iteration.saturating_add(1),
                episodes: options.rollout_episodes,
            },
        ) {
            break;
        }
        let batch = collect_batch(
            &learners,
            config.clone(),
            seeds,
            iteration,
            options.rollout_episodes,
            &algorithm,
            nursery_beta,
            phase,
            &historical_opponents,
            competition_promotion.is_scarce(),
            capture_visual_batch,
        )?;
        #[cfg(feature = "render")]
        let mut batch = batch;
        global_steps = global_steps.saturating_add(batch.joint_steps);
        // Publish the collected trajectories before optimization starts. Bevy
        // can replay them while PPO consumes the same frozen-policy batch.
        #[cfg(feature = "render")]
        if let Some(trace) = batch.visual_trace.take() {
            let receiver_closed = batch_reporter
                .as_mut()
                .is_some_and(|callback| !callback(trace));
            if receiver_closed {
                break;
            }
        }
        #[cfg(feature = "render")]
        if !report_activity(
            &mut activity_reporter,
            TrainerActivity::Optimization {
                iteration: iteration.saturating_add(1),
            },
        ) {
            break;
        }
        let bunny_update =
            if policy_update_available(phase.updates_bunny(), batch.bunny_sequences.len()) {
                if iteration < critic_warmup_iterations {
                    Some(learners.bunny.update_critic(&batch.bunny_sequences)?)
                } else {
                    Some(learners.bunny.update(&batch.bunny_sequences)?)
                }
            } else {
                None
            };
        let fox_update = if policy_update_available(phase.updates_fox(), batch.fox_sequences.len())
        {
            if let Some(fox) = learners.fox.as_mut() {
                Some(fox.update(&batch.fox_sequences)?)
            } else {
                None
            }
        } else {
            None
        };
        let bunny_lifetime = mean(&batch.bunny_lifetimes);
        let fox_lifetime = mean(&batch.fox_lifetimes);
        let bunny_return = mean(&batch.bunny_returns);
        let fox_return = mean(&batch.fox_returns);
        let update = combine_updates(bunny_update, fox_update);
        write_training_metric(
            &mut metrics,
            global_steps,
            iteration + 1,
            bunny_return,
            fox_return,
            bunny_lifetime,
            fox_lifetime,
            update,
            nursery_beta,
            config.experiment_tuning(),
        )?;
        let should_evaluate = (iteration + 1).is_multiple_of(options.eval_interval)
            || iteration + 1 == options.iterations;
        let mut evaluation = None;
        let mut is_best = false;
        if should_evaluate {
            #[cfg(feature = "render")]
            if !report_activity(
                &mut activity_reporter,
                TrainerActivity::Evaluation {
                    iteration: iteration.saturating_add(1),
                    episodes: training_validation_episode_count(stage, options.eval_episodes),
                },
            ) {
                break;
            }
            let result = evaluate_training_iteration(
                EvaluationPass {
                    stage,
                    learners: &learners,
                    config: &config,
                    paths: &paths,
                    options: &options,
                    metrics: &mut metrics,
                    validation_seed: seeds.validation,
                    has_foxes,
                    survival_retention: survival_retention.as_ref(),
                },
                global_steps,
                best_evaluation,
            )?;
            is_best = result.1;
            if result.1 {
                best_evaluation = result.0;
            }
            if let Some(expanded_baseline) = promote_forage_if_ready(
                stage,
                &mut forage_promotion,
                result.0,
                &mut learners,
                &mut config,
                &paths,
                &options,
                &algorithm,
                seeds,
                &mut metrics,
                global_steps,
            )? {
                best_evaluation = expanded_baseline;
                profile_baseline = expanded_baseline;
                is_best = true;
                evaluation = Some(expanded_baseline);
            }
            if matches!(stage, CurriculumStage::PredatorPrey)
                && iteration + 1 >= 4
                && result.0.episodes_with_predation > 0
            {
                fox_acquired = true;
            }
            if stage == CurriculumStage::Competition && competition_promotion.record(result.0) {
                // Reset Adam after the validated change from abundant lessons
                // to a retained abundant-and-scarce collection mixture.
                learners.bunny = RecurrentPpoAgent::load(
                    &paths.best_checkpoint,
                    LOCAL_OBSERVATION_SIZE,
                    GLOBAL_STATE_SIZE,
                    MAX_AGENTS,
                    &ACTION_LOW,
                    &ACTION_HIGH,
                    algorithm.clone(),
                    SeedConfig::from_root(seeds.model),
                )?;
            }
            if evaluation.is_none() {
                evaluation = Some(result.0);
            }
        }
        let displayed_evaluation = evaluation.unwrap_or(best_evaluation);
        write_iteration_output(
            &mut output,
            stage,
            iteration + 1,
            global_steps,
            bunny_return,
            fox_return,
            bunny_lifetime,
            fox_lifetime,
            displayed_evaluation,
            update,
            is_best,
        )?;
        historical_opponents.record(&learners, iteration + 1, options.iterations, is_best);
        // Send the current policy after its metrics and checkpoint are durable.
        #[cfg(feature = "render")]
        if !report_training_update(
            &mut reporter,
            &learners,
            &config,
            &paths,
            &options,
            iteration + 1,
            global_steps,
            bunny_return,
            fox_return,
            &batch.bunny_returns,
            &batch.fox_returns,
            displayed_evaluation,
            update,
            is_best,
            evaluation.is_some(),
        ) {
            break;
        }
    }
    write_summary(
        &paths,
        stage,
        global_steps,
        profile_baseline,
        best_evaluation,
    )?;
    writeln!(output, "run_dir={}", paths.run_dir.display())?;
    Ok(())
}

/// Evaluate, persist, and classify one scheduled policy snapshot.
fn evaluate_training_iteration(
    pass: EvaluationPass<'_>,
    global_steps: u64,
    prior_best: EvaluationSummary,
) -> Result<(EvaluationSummary, bool), Box<dyn Error>> {
    let summary = evaluate_learners(
        pass.learners,
        pass.config.clone(),
        pass.validation_seed,
        pass.options.eval_episodes,
    )?;
    save_checkpoint_set(
        pass.stage,
        pass.learners,
        pass.paths,
        CheckpointKind::Latest,
        pass.config,
    )?;
    save_checkpoint_set(
        pass.stage,
        pass.learners,
        pass.paths,
        CheckpointKind::Step(global_steps),
        pass.config,
    )?;
    let retention = evaluate_survival_retention(pass.survival_retention, pass.learners)?;
    write_survival_retention_metric(
        pass.metrics,
        global_steps,
        retention,
        pass.config.experiment_tuning(),
    )?;
    let is_best = retention.is_none_or(|result| result.passed)
        && summary.checkpoint_is_better_than(prior_best, pass.stage, pass.has_foxes);
    if is_best {
        save_checkpoint_set(
            pass.stage,
            pass.learners,
            pass.paths,
            CheckpointKind::Best,
            pass.config,
        )?;
    }
    write_evaluation_metric(
        pass.metrics,
        global_steps,
        summary,
        is_best,
        pass.config.experiment_tuning(),
    )?;
    Ok((summary, is_best))
}

/// Promote forage after three passes and restart selection with fresh optimizers.
#[expect(
    clippy::too_many_arguments,
    reason = "promotion persists one atomic policy, profile, metric, and optimizer transition"
)]
fn promote_forage_if_ready(
    stage: CurriculumStage,
    promotion: &mut ForagePromotion,
    validation: EvaluationSummary,
    learners: &mut Learners,
    config: &mut SimulationConfig,
    paths: &RunPaths,
    options: &TrainOptions,
    algorithm: &RecurrentPpoConfig,
    seeds: SeedConfig,
    metrics: &mut MetricsWriter,
    global_steps: u64,
) -> Result<Option<EvaluationSummary>, Box<dyn Error>> {
    if stage != CurriculumStage::Forage || !promotion.record(validation) {
        return Ok(None);
    }

    // Persist the harder environment before replacing the selection baseline.
    config.forage_difficulty = promotion.difficulty();
    write_run_config(paths, stage, options, algorithm, seeds, config)?;
    save_checkpoint_set(stage, learners, paths, CheckpointKind::Best, config)?;
    save_checkpoint_set(stage, learners, paths, CheckpointKind::Latest, config)?;

    // Loading the unchanged networks resets Adam state after the distribution change.
    learners.bunny = RecurrentPpoAgent::load(
        &paths.best_checkpoint,
        LOCAL_OBSERVATION_SIZE,
        GLOBAL_STATE_SIZE,
        MAX_AGENTS,
        &ACTION_LOW,
        &ACTION_HIGH,
        algorithm.clone(),
        SeedConfig::from_root(seeds.model),
    )?;
    let expert_samples = forage_expert_samples(
        config.clone(),
        seeds.environment_episode(0, global_steps),
        FORAGE_EXPERT_SAMPLE_COUNT,
    )?;
    let mut clone_loss = 0.0;
    for _ in 0..FORAGE_BEHAVIOR_CLONE_UPDATES {
        clone_loss = learners.bunny.behavior_clone(&expert_samples)?;
    }
    let clone_record = MetricRecord::new(global_steps)
        .with_field(
            "train/forage_behavior_clone_loss",
            MetricValue::Number(clone_loss),
        )
        .with_field(
            "train/forage_behavior_clone_samples",
            MetricValue::Number(FORAGE_EXPERT_SAMPLE_COUNT as f64),
        )
        .with_field(
            "train/forage_behavior_clone_updates",
            MetricValue::Number(FORAGE_BEHAVIOR_CLONE_UPDATES as f64),
        );
    metrics.write_record(&with_experiment_metrics(
        clone_record,
        config.experiment_tuning(),
    ))?;
    let baseline = evaluate_learners(
        learners,
        config.clone(),
        seeds.validation,
        options.eval_episodes,
    )?;
    save_checkpoint_set(stage, learners, paths, CheckpointKind::Best, config)?;
    write_evaluation_metric(
        metrics,
        global_steps,
        baseline,
        true,
        config.experiment_tuning(),
    )?;
    Ok(Some(baseline))
}

/// Apply a changed HUD profile and restart checkpoint selection on that profile.
#[cfg(feature = "render")]
fn apply_training_tuning(
    provider: &mut dyn FnMut() -> ExperimentTuning,
    config: &mut SimulationConfig,
    persistence: TuningPersistence<'_>,
) -> Result<Option<EvaluationSummary>, Box<dyn Error>> {
    let next_tuning = provider();
    if next_tuning == config.experiment_tuning() {
        return Ok(None);
    }
    config.apply_experiment_tuning(next_tuning)?;
    write_run_config(
        persistence.paths,
        persistence.stage,
        persistence.options,
        persistence.algorithm,
        persistence.seeds,
        config,
    )?;
    let baseline = evaluate_learners(
        persistence.learners,
        config.clone(),
        persistence.seeds.validation,
        persistence.options.eval_episodes,
    )?;
    save_checkpoint_set(
        persistence.stage,
        persistence.learners,
        persistence.paths,
        CheckpointKind::Best,
        config,
    )?;
    Ok(Some(baseline))
}

