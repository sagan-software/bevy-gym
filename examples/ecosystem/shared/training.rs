/// Evaluate independent fixed-seed episodes under one frozen policy snapshot.
fn evaluate_policy_episodes(
    bunny: &RecurrentPpoPolicy,
    fox: Option<&RecurrentPpoPolicy>,
    config: &SimulationConfig,
    validation_seed: u64,
    episodes: usize,
    food_perception: FoodPerceptionProfile,
    episode_seed: fn(u64, usize) -> u64,
    strategy: EvaluationStrategy,
) -> Result<Vec<DeterministicEpisode>, Box<dyn Error>> {
    let evaluate = |episode| {
        let seed = episode_seed(validation_seed, episode);
        deterministic_episode(config.clone(), seed, episode, bunny, fox, food_perception)
    };
    if strategy == EvaluationStrategy::Sequential || episodes <= 1 {
        return (0..episodes).map(evaluate).collect();
    }

    let available_workers = std::thread::available_parallelism().map_or(1, usize::from);
    let worker_count = available_workers.min(episodes).max(1);
    let episodes_per_worker = episodes.div_ceil(worker_count);
    std::thread::scope(|scope| {
        let handles = (0..episodes)
            .step_by(episodes_per_worker)
            .map(|start| {
                let end = start.saturating_add(episodes_per_worker).min(episodes);
                let evaluate = &evaluate;
                scope.spawn(move || {
                    (start..end)
                        .map(|episode| evaluate(episode).map_err(|error| error.to_string()))
                        .collect::<Result<Vec<_>, _>>()
                })
            })
            .collect::<Vec<_>>();
        let mut results = Vec::with_capacity(episodes);
        for handle in handles {
            let joined = handle.join();
            match joined {
                Ok(Ok(mut worker_results)) => results.append(&mut worker_results),
                Ok(Err(message)) => return Err(io::Error::other(message).into()),
                Err(_) => {
                    return Err(io::Error::other("evaluation worker panicked").into());
                }
            }
        }
        Ok(results)
    })
}

/// Run one evaluation episode without exploration or centralized actor input.
fn deterministic_episode(
    config: SimulationConfig,
    seed: u64,
    spawn_rotation: usize,
    bunny: &RecurrentPpoPolicy,
    fox: Option<&RecurrentPpoPolicy>,
    food_perception: FoodPerceptionProfile,
) -> Result<DeterministicEpisode, Box<dyn Error>> {
    let mut ecosystem = Ecosystem::new_rotated(config, seed, spawn_rotation)?;
    let mut current = ecosystem.state();
    let mut memories = BTreeMap::<AgentId, RecurrentMemory>::new();
    let mut bunny_left_food_turns = Vec::new();
    let mut bunny_right_food_turns = Vec::new();
    loop {
        let mut actions = Vec::with_capacity(current.agents.len());
        let mut next_memories = BTreeMap::new();
        for (id, species, observation) in &current.agents {
            let policy = match species {
                Species::Bunny => bunny,
                Species::Fox => fox.ok_or("fox agent exists without an evaluation policy")?,
            };
            let memory = memories
                .entry(*id)
                .or_insert_with(|| policy.initial_memory());
            let mut actor_observation = *observation;
            if matches!(food_perception, FoodPerceptionProfile::Ablated) {
                ablate_food_perception(&mut actor_observation);
            }
            let action = policy.mean_action(&actor_observation, memory)?;
            let [forward, turn, gaze, attack] = action.action.as_slice() else {
                return Err("ecosystem policy must emit exactly four action axes".into());
            };
            if species == &Species::Bunny {
                let food_bearing = observed_ray_bearing(observation, PerceptKind::Food);
                if food_bearing.is_some_and(|bearing| bearing > 0.1) {
                    bunny_left_food_turns.push(*turn);
                } else if food_bearing.is_some_and(|bearing| bearing < -0.1) {
                    bunny_right_food_turns.push(*turn);
                }
            }
            actions.push((*id, LocomotionAction::new(*forward, *turn, *gaze, *attack)?));
            next_memories.insert(*id, action.next_memory);
        }
        let result = ecosystem.step(&actions)?;
        let mut next_agents = Vec::new();
        for agent_step in result.agents {
            if agent_step.status == EpisodeStatus::Continuing {
                if let Some(memory) = next_memories.remove(&agent_step.id) {
                    memories.insert(agent_step.id, memory);
                }
                next_agents.push((agent_step.id, agent_step.species, agent_step.observation));
            } else {
                memories.remove(&agent_step.id);
            }
        }
        if result.is_done {
            break;
        }
        current.agents = next_agents;
        current.global_state = result.global_state;
    }
    Ok(DeterministicEpisode {
        agents: ecosystem.episode_metrics(),
        bunny_left_food_turns,
        bunny_right_food_turns,
    })
}

/// Remove every food ray from one actor input.
fn ablate_food_perception(observation: &mut LocalObservation) {
    // Clear the complete matching ray so distance cannot leak food visibility.
    for ray_index in 0..RAY_COUNT {
        let start = PROPRIOCEPTION_SIZE + ray_index * RAY_FEATURE_SIZE;
        let food_channel = start + RAY_KIND_START + PerceptKind::Food.index();
        if observation
            .get(food_channel)
            .is_some_and(|value| *value > 0.5)
        {
            if let Some(ray) = observation.get_mut(start..start + RAY_FEATURE_SIZE) {
                ray.fill(0.0);
            }
        }
    }
}

/// Return the nearest ray index and distance for one semantic class.
fn nearest_observed_ray(observation: &LocalObservation, kind: PerceptKind) -> Option<(usize, f32)> {
    // Total float ordering keeps nearest-hit selection deterministic.
    (0..RAY_COUNT)
        .filter_map(|ray_index| {
            let start = PROPRIOCEPTION_SIZE + ray_index * RAY_FEATURE_SIZE;
            let distance = *observation.get(start)?;
            let kind_value = observation.get(start + RAY_KIND_START + kind.index())?;
            (*kind_value > 0.5).then_some((ray_index, distance))
        })
        .min_by(|(_, left), (_, right)| left.total_cmp(right))
}

/// Return the configured bearing of the nearest matching perception ray.
fn observed_ray_bearing(observation: &LocalObservation, kind: PerceptKind) -> Option<f32> {
    let (ray_index, _) = nearest_observed_ray(observation, kind)?;
    RAY_ANGLES.get(ray_index).copied()
}

/// Return the midpoint median after deterministic total ordering.
fn median(values: &mut [f32]) -> f32 {
    if values.is_empty() {
        return 0.0;
    }
    values.sort_by(f32::total_cmp);
    let middle = values.len() / 2;
    if values.len().is_multiple_of(2) {
        let Some((lower, upper)) = values
            .get(middle - 1)
            .copied()
            .zip(values.get(middle).copied())
        else {
            return 0.0;
        };
        (lower + upper) * 0.5
    } else {
        values.get(middle).map_or(0.0, |value| *value)
    }
}

/// Weight update diagnostics by each updated species' valid agent-time contribution.
fn combine_updates(
    bunny: Option<RecurrentPpoUpdate>,
    fox: Option<RecurrentPpoUpdate>,
) -> UpdateSummary {
    let bunny_valid_samples = bunny.map_or(0, |update| update.valid_samples);
    let fox_valid_samples = fox.map_or(0, |update| update.valid_samples);
    let valid_samples = bunny_valid_samples.saturating_add(fox_valid_samples);
    let divisor = valid_samples as f64;
    let bunny_weight = if valid_samples == 0 {
        0.0
    } else {
        bunny_valid_samples as f64 / divisor
    };
    let fox_weight = if valid_samples == 0 {
        0.0
    } else {
        fox_valid_samples as f64 / divisor
    };

    // Policies retain separate optimizers, but their diagnostics describe one
    // joint batch and therefore share the agent-time denominator.
    UpdateSummary {
        valid_samples,
        optimizer_updates: bunny
            .map_or(0, |update| update.optimizer_updates)
            .saturating_add(fox.map_or(0, |update| update.optimizer_updates)),
        actor_loss: bunny.map_or(0.0, |update| update.actor_loss).mul_add(
            bunny_weight,
            fox.map_or(0.0, |update| update.actor_loss) * fox_weight,
        ),
        critic_loss: bunny.map_or(0.0, |update| update.critic_loss).mul_add(
            bunny_weight,
            fox.map_or(0.0, |update| update.critic_loss) * fox_weight,
        ),
        entropy: bunny.map_or(0.0, |update| update.entropy).mul_add(
            bunny_weight,
            fox.map_or(0.0, |update| update.entropy) * fox_weight,
        ),
        approximate_kl: bunny.map_or(0.0, |update| update.approximate_kl).mul_add(
            bunny_weight,
            fox.map_or(0.0, |update| update.approximate_kl) * fox_weight,
        ),
        actor_learning_rate: bunny.map_or_else(
            || fox.map_or(0.0, |update| update.actor_learning_rate),
            |update| update.actor_learning_rate,
        ),
        critic_learning_rate: bunny.map_or_else(
            || fox.map_or(0.0, |update| update.critic_learning_rate),
            |update| update.critic_learning_rate,
        ),
    }
}

