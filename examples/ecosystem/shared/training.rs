/// Read and validate one exact checkpoint's stage and tuning profile.
fn checkpoint_profile(checkpoint: &Path) -> Result<(String, ExperimentTuning), Box<dyn Error>> {
    let profile = read_checkpoint_profile(checkpoint)?;
    validate_checkpoint_profile(profile.profile_version, &profile.stage)?;
    Ok((
        profile.stage,
        ExperimentTuning::try_from(profile.experiment_tuning)?,
    ))
}

/// Read one checkpoint companion without accepting its compatibility profile.
fn read_checkpoint_profile(checkpoint: &Path) -> Result<CheckpointProfile, Box<dyn Error>> {
    let config_path = checkpoint_config_path(checkpoint);
    if !config_path.exists() {
        return Err(format!(
            "checkpoint requires a companion profile-{} config: {}",
            CHECKPOINT_PROFILE,
            config_path.display()
        )
        .into());
    }
    Ok(serde_json::from_reader(File::open(config_path)?)?)
}

/// Reject a checkpoint created for a different curriculum stage.
pub(super) fn validate_checkpoint_stage(
    checkpoint: &Path,
    expected: CurriculumStage,
) -> Result<(), Box<dyn Error>> {
    let (actual, _) = checkpoint_profile(checkpoint)?;
    if actual == expected.as_key() {
        Ok(())
    } else {
        Err(format!(
            "checkpoint stage {actual} is incompatible with required stage {}: {}",
            expected.as_key(),
            checkpoint.display()
        )
        .into())
    }
}

/// Accept a policy trained on this stage or any later curriculum stage for retention evaluation.
fn validate_evaluation_checkpoint_stage(
    checkpoint: &Path,
    environment: CurriculumStage,
) -> Result<(), Box<dyn Error>> {
    let (actual, _) = checkpoint_profile(checkpoint)?;
    let actual_stage = CurriculumStage::ALL
        .into_iter()
        .find(|stage| stage.as_key() == actual)
        .ok_or_else(|| format!("checkpoint has unknown curriculum stage {actual}"))?;
    if actual_stage.index() >= environment.index() {
        Ok(())
    } else {
        Err(format!(
            "checkpoint stage {actual} predates evaluation environment {}: {}",
            environment.as_key(),
            checkpoint.display()
        )
        .into())
    }
}

/// Accept a current-stage or direct-predecessor policy for curriculum transfer.
fn validate_resume_checkpoint_stage(
    checkpoint: &Path,
    target: CurriculumStage,
) -> Result<(), Box<dyn Error>> {
    let profile = read_checkpoint_profile(checkpoint)?;
    validate_checkpoint_profile(profile.profile_version, &profile.stage)?;
    let actual = profile.stage;
    let predecessor = predecessor_stage(target);
    if actual == target.as_key() || predecessor.is_some_and(|stage| actual == stage.as_key()) {
        Ok(())
    } else {
        Err(format!(
            "checkpoint stage {actual} cannot resume target stage {}: {}",
            target.as_key(),
            checkpoint.display()
        )
        .into())
    }
}

/// Return the direct checkpoint and rehearsal predecessor for one stage.
const fn predecessor_stage(stage: CurriculumStage) -> Option<CurriculumStage> {
    // Encode the only checkpoint transfer edge accepted for each stage.
    match stage {
        CurriculumStage::Forage => None,
        CurriculumStage::Sprint => Some(CurriculumStage::Forage),
        CurriculumStage::Gorge => Some(CurriculumStage::Sprint),
        CurriculumStage::Survival => Some(CurriculumStage::Gorge),
        CurriculumStage::Shelter => Some(CurriculumStage::Survival),
        CurriculumStage::Competition => Some(CurriculumStage::Shelter),
        CurriculumStage::PredatorPrey => Some(CurriculumStage::Competition),
        CurriculumStage::Obstacles => Some(CurriculumStage::PredatorPrey),
    }
}

/// Return whether one continuation checkpoint already belongs to the target stage.
fn resume_uses_current_stage(
    stage: CurriculumStage,
    resume: Option<&Path>,
) -> Result<bool, Box<dyn Error>> {
    let Some(resume) = resume else {
        return Ok(false);
    };
    let checkpoint = resolve_bunny_checkpoint(resume);
    let profile = read_checkpoint_profile(&checkpoint)?;
    validate_checkpoint_profile(profile.profile_version, &profile.stage)?;
    Ok(profile.stage == stage.as_key())
}

/// Return the bounded critic-only window for a direct competition transfer.
const fn competition_critic_warmup_iterations(
    has_resume: bool,
    resume_is_current_stage: bool,
) -> usize {
    if has_resume && !resume_is_current_stage {
        COMPETITION_CRITIC_WARMUP_ITERATIONS
    } else {
        0
    }
}

