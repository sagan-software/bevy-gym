impl EvaluationSummary {
    /// Score used only for best-checkpoint selection.
    const fn selection_score(self, has_foxes: bool) -> f32 {
        if has_foxes {
            self.bunny_mean_return.min(self.fox_mean_return)
        } else {
            self.bunny_mean_return
        }
    }

    /// Resolve a decisive speed-lesson comparison or preserve a complete tie.
    fn movement_checkpoint_comparison(self, prior: Self, stage: CurriculumStage) -> Option<bool> {
        // Prefer complete behavior gates before ranking partial progress.
        let time_limit = if stage == CurriculumStage::Sprint {
            4.0
        } else {
            5.0
        };
        let passes_behavior =
            self.bunny_food_fraction >= 0.80 && self.bunny_mean_time_to_contact <= time_limit;
        let prior_passes_behavior =
            prior.bunny_food_fraction >= 0.80 && prior.bunny_mean_time_to_contact <= time_limit;
        if passes_behavior != prior_passes_behavior {
            return Some(passes_behavior);
        }
        match self
            .bunny_food_fraction
            .partial_cmp(&prior.bunny_food_fraction)
        {
            Some(std::cmp::Ordering::Greater) => return Some(true),
            Some(std::cmp::Ordering::Less) => return Some(false),
            Some(std::cmp::Ordering::Equal) | None => {}
        }
        if stage == CurriculumStage::Gorge && self.deaths.gorge != prior.deaths.gorge {
            return Some(self.deaths.gorge < prior.deaths.gorge);
        }
        if passes_behavior {
            match self
                .bunny_mean_time_to_contact
                .partial_cmp(&prior.bunny_mean_time_to_contact)
            {
                Some(std::cmp::Ordering::Less) => return Some(true),
                Some(std::cmp::Ordering::Greater) => return Some(false),
                Some(std::cmp::Ordering::Equal) | None => {}
            }
        }
        None
    }

    /// Compare validation snapshots against the current stage contract.
    fn checkpoint_is_better_than(
        self,
        prior: Self,
        stage: CurriculumStage,
        has_foxes: bool,
    ) -> bool {
        // Apply each stage's behavior gate before the generic return score.
        if stage == CurriculumStage::Forage {
            let passes_behavior = forage_selection_gates(self);
            let prior_passes_behavior = forage_selection_gates(prior);
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
        }
        if matches!(stage, CurriculumStage::Sprint | CurriculumStage::Gorge) {
            if let Some(is_better) = self.movement_checkpoint_comparison(prior, stage) {
                return is_better;
            }
        }
        if stage == CurriculumStage::Survival {
            let passes_behavior = self.bunny_food_and_water_fraction >= 0.80;
            let prior_passes_behavior = prior.bunny_food_and_water_fraction >= 0.80;
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
            if passes_behavior {
                match self
                    .bunny_full_horizon_fraction
                    .partial_cmp(&prior.bunny_full_horizon_fraction)
                {
                    Some(std::cmp::Ordering::Greater) => return true,
                    Some(std::cmp::Ordering::Less) => return false,
                    Some(std::cmp::Ordering::Equal) | None => {}
                }
                match self
                    .bunny_terminal_max_stats_fraction
                    .partial_cmp(&prior.bunny_terminal_max_stats_fraction)
                {
                    Some(std::cmp::Ordering::Greater) => return true,
                    Some(std::cmp::Ordering::Less) => return false,
                    Some(std::cmp::Ordering::Equal) | None => {}
                }
            } else {
                match self
                    .bunny_food_and_water_fraction
                    .partial_cmp(&prior.bunny_food_and_water_fraction)
                {
                    Some(std::cmp::Ordering::Greater) => return true,
                    Some(std::cmp::Ordering::Less) => return false,
                    Some(std::cmp::Ordering::Equal) | None => {}
                }
            }
        }
        if stage == CurriculumStage::Shelter {
            let passes_behavior = self.bunny_shelter_before_critical_fraction >= 0.80;
            let prior_passes_behavior = prior.bunny_shelter_before_critical_fraction >= 0.80;
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
            if passes_behavior && self.deaths.exposure != prior.deaths.exposure {
                return self.deaths.exposure < prior.deaths.exposure;
            }
            match self
                .bunny_shelter_before_critical_fraction
                .partial_cmp(&prior.bunny_shelter_before_critical_fraction)
            {
                Some(std::cmp::Ordering::Greater) => return true,
                Some(std::cmp::Ordering::Less) => return false,
                Some(std::cmp::Ordering::Equal) | None => {}
            }
        }
        if stage == CurriculumStage::Competition {
            let passes_behavior = self.bunny_resource_consumer_count >= 4
                && self.bunny_index_lifetime_advantage_fraction <= 0.20
                && self.contact_displacements >= 1;
            let prior_passes_behavior = prior.bunny_resource_consumer_count >= 4
                && prior.bunny_index_lifetime_advantage_fraction <= 0.20
                && prior.contact_displacements >= 1;
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
            if passes_behavior {
                match self
                    .bunny_mean_lifetime
                    .partial_cmp(&prior.bunny_mean_lifetime)
                {
                    Some(std::cmp::Ordering::Greater) => return true,
                    Some(std::cmp::Ordering::Less) => return false,
                    Some(std::cmp::Ordering::Equal) | None => {}
                }
            }
        }
        if stage == CurriculumStage::PredatorPrey {
            let episode_count = self
                .episodes_with_predation
                .saturating_add(self.episodes_without_predation);
            let prior_episode_count = prior
                .episodes_with_predation
                .saturating_add(prior.episodes_without_predation);
            let passes_behavior = episode_count > 0
                && self.episodes_with_predation.saturating_mul(10) >= episode_count;
            let prior_passes_behavior = prior_episode_count > 0
                && prior.episodes_with_predation.saturating_mul(10) >= prior_episode_count;
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
            if !passes_behavior {
                let predation_order = u64::from(self.episodes_with_predation)
                    .saturating_mul(u64::from(prior_episode_count))
                    .cmp(
                        &u64::from(prior.episodes_with_predation)
                            .saturating_mul(u64::from(episode_count)),
                    );
                if predation_order != std::cmp::Ordering::Equal {
                    return predation_order == std::cmp::Ordering::Greater;
                }
            }
            let bunny_order = self
                .bunny_mean_lifetime
                .partial_cmp(&prior.bunny_mean_lifetime);
            let fox_order = self.fox_mean_lifetime.partial_cmp(&prior.fox_mean_lifetime);
            let neither_regressed = matches!(
                bunny_order,
                Some(std::cmp::Ordering::Equal | std::cmp::Ordering::Greater)
            ) && matches!(
                fox_order,
                Some(std::cmp::Ordering::Equal | std::cmp::Ordering::Greater)
            );
            let one_improved = bunny_order == Some(std::cmp::Ordering::Greater)
                || fox_order == Some(std::cmp::Ordering::Greater);
            return neither_regressed && one_improved;
        }
        if stage == CurriculumStage::Obstacles {
            let passes_behavior =
                self.unresolved_solid_penetrations == 0 && self.bunny_mean_lifetime >= 10.0;
            let prior_passes_behavior =
                prior.unresolved_solid_penetrations == 0 && prior.bunny_mean_lifetime >= 10.0;
            if passes_behavior != prior_passes_behavior {
                return passes_behavior;
            }
            if passes_behavior {
                match self
                    .thorn_damage_per_agent_minute
                    .partial_cmp(&prior.thorn_damage_per_agent_minute)
                {
                    Some(std::cmp::Ordering::Less) => return true,
                    Some(std::cmp::Ordering::Greater) => return false,
                    Some(std::cmp::Ordering::Equal) | None => {}
                }
            }
        }
        self.selection_score(has_foxes) > prior.selection_score(has_foxes)
    }
}

/// Return whether one validation summary satisfies every forage behavior gate.
fn forage_selection_gates(summary: EvaluationSummary) -> bool {
    summary.bunny_food_fraction >= 0.90
        && summary.bunny_left_food_median_turn > 0.0
        && summary.bunny_right_food_median_turn < 0.0
        && summary.bunny_food_fraction - summary.bunny_ablated_food_fraction >= 0.50
}

