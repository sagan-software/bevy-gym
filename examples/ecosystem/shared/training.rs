impl TrainOptions {
    /// Select stage-specific defaults without changing explicit CLI overrides.
    fn for_stage(stage: CurriculumStage) -> Self {
        let mut options = Self::default();
        if stage == CurriculumStage::Survival {
            // The longer horizon leaves room for the required 30% lifetime gain.
            options.iterations = 16;
            options.rollout_episodes = SURVIVAL_BATCH_ENVIRONMENTS;
            options.episode_seconds = 120;
            options.seed = 157;
            options.eval_episodes = 16;
            options.eval_interval = 4;
        }
        if !matches!(stage, CurriculumStage::Forage) {
            options.log_std_max = -0.5;
        }
        options
    }
}

