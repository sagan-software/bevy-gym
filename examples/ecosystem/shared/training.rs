/// Closed actor-input profile for forage ablation evidence.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FoodPerceptionProfile {
    /// Preserve every food summary and semantic ray channel.
    Full,
    /// Remove food summaries and complete food-ray observations.
    Ablated,
}

impl FromStr for FoodPerceptionProfile {
    type Err = String;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "full" => Ok(Self::Full),
            "ablated" => Ok(Self::Ablated),
            _ => Err(format!(
                "food perception profile must be full or ablated, got {value:?}"
            )),
        }
    }
}

