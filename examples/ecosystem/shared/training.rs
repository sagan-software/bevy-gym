/// Return zero for an absent species or the arithmetic lifetime mean.
fn mean(values: &[f32]) -> f32 {
    if values.is_empty() {
        0.0
    } else {
        values.iter().sum::<f32>() / values.len() as f32
    }
}

/// Largest relative identity advantage above the stable population mean.
fn index_lifetime_advantage(lifetimes_by_id: &[Vec<f32>]) -> f32 {
    let means = lifetimes_by_id
        .iter()
        .filter(|values| !values.is_empty())
        .map(|values| mean(values))
        .collect::<Vec<_>>();
    let population_mean = mean(&means);
    if population_mean <= f32::EPSILON {
        return 0.0;
    }
    let maximum = means.iter().copied().fold(f32::NEG_INFINITY, f32::max);
    (maximum - population_mean) / population_mean
}

/// Initialize one parameter-sharing learner per species present.
fn create_learners(
    stage: CurriculumStage,
    config: &SimulationConfig,
    algorithm: &RecurrentPpoConfig,
    seeds: SeedConfig,
    options: &TrainOptions,
) -> Result<Learners, Box<dyn Error>> {
    let create = |seed| {
        RecurrentPpoAgent::new(
            LOCAL_OBSERVATION_SIZE,
            GLOBAL_STATE_SIZE,
            MAX_AGENTS,
            &ACTION_LOW,
            &ACTION_HIGH,
            algorithm.clone(),
            SeedConfig::from_root(seed),
        )
    };
    let load = |path: &Path, seed| -> Result<RecurrentPpoAgent, Box<dyn Error>> {
        validate_resume_checkpoint_stage(path, stage)?;
        let profile = read_checkpoint_profile(path)?;
        let _tuning = ExperimentTuning::try_from(profile.experiment_tuning)?;
        let seeds = SeedConfig::from_root(seed);
        if resume_uses_current_stage(stage, Some(path))? {
            Ok(RecurrentPpoAgent::load(
                path,
                LOCAL_OBSERVATION_SIZE,
                GLOBAL_STATE_SIZE,
                MAX_AGENTS,
                &ACTION_LOW,
                &ACTION_HIGH,
                algorithm.clone(),
                seeds,
            )?)
        } else {
            let mut agent = RecurrentPpoAgent::load_actor_with_fresh_critic(
                path,
                LOCAL_OBSERVATION_SIZE,
                GLOBAL_STATE_SIZE,
                MAX_AGENTS,
                &ACTION_LOW,
                &ACTION_HIGH,
                algorithm.clone(),
                seeds,
            )?;
            let predecessor = predecessor_stage(stage)
                .ok_or("direct actor transfer requires a predecessor stage")?;
            copy_direct_predecessor_actor_features(&mut agent, predecessor, stage)?;
            Ok(agent)
        }
    };
    let bunny_resume = options.resume.as_deref().map(resolve_bunny_checkpoint);
    let bunny = if let Some(path) = &bunny_resume {
        load(path, seeds.model)?
    } else {
        create(seeds.model)?
    };
    let fox_seed = seeds.model ^ 0x666f_785f_706f_6c69;
    let fox = if config.fox_count == 0 {
        None
    } else if let Some(path) = &options.fox_resume {
        if let Some(bunny_path) = &bunny_resume {
            validate_checkpoint_tuning_match(bunny_path, path)?;
        }
        Some(load(path, fox_seed)?)
    } else if let Some(bunny_path) = &bunny_resume {
        let inferred = sibling_fox_checkpoint(bunny_path);
        if inferred.is_file() {
            validate_checkpoint_tuning_match(bunny_path, &inferred)?;
            Some(load(&inferred, fox_seed)?)
        } else {
            // Preserve predecessor resource navigation in the new species while
            // keeping its centralized value function independently initialized.
            Some(load(bunny_path, fox_seed)?)
        }
    } else {
        Some(create(fox_seed)?)
    };
    Ok(Learners { bunny, fox })
}

/// Copy actor inputs whose meanings continue across a direct curriculum transition.
fn copy_direct_predecessor_actor_features(
    agent: &mut RecurrentPpoAgent,
    predecessor: CurriculumStage,
    target: CurriculumStage,
) -> Result<(), Box<dyn Error>> {
    match (predecessor, target) {
        (CurriculumStage::Gorge, CurriculumStage::Survival) => {
            // Water need and rays reuse the established food-navigation inputs.
            agent.copy_actor_input_feature(0, 1)?;
            for ray_index in 0..RAY_COUNT {
                let start = PROPRIOCEPTION_SIZE + ray_index * RAY_FEATURE_SIZE;
                agent.copy_actor_input_feature(
                    start + RAY_KIND_START + PerceptKind::Food.index(),
                    start + RAY_KIND_START + PerceptKind::Well.index(),
                )?;
            }
        }
        (CurriculumStage::Survival, CurriculumStage::Shelter) => {
            // Exposure reserve and shelter perception reuse the established
            // water-need and well-navigation actor behavior at promotion.
            agent.copy_actor_input_feature(1, LOCAL_EXPOSURE_INDEX)?;
            for ray_index in 0..RAY_COUNT {
                let start = PROPRIOCEPTION_SIZE + ray_index * RAY_FEATURE_SIZE;
                agent.copy_actor_input_feature(
                    start + RAY_KIND_START + PerceptKind::Well.index(),
                    start + RAY_KIND_START + PerceptKind::Shelter.index(),
                )?;
            }
        }
        _ => {}
    }
    Ok(())
}

/// Freeze one behavior policy per species for an on-policy episode.
fn collection_policies(
    learners: &Learners,
    seeds: SeedConfig,
    sample_index: u64,
    iteration: usize,
    phase: TrainingPhase,
    opponents: &HistoricalOpponents,
) -> CollectionPolicies {
    let role = opponent_role(phase, iteration);
    let current_bunny = learners.bunny.policy();
    let current_fox = learners.fox.as_ref().map(RecurrentPpoAgent::policy);
    let bunny = if matches!(phase, TrainingPhase::Fox) {
        opponents.bunny(current_bunny, role)
    } else {
        current_bunny
    };
    let fox = if matches!(phase, TrainingPhase::Bunny) {
        opponents.fox(current_fox, role)
    } else {
        current_fox
    };
    CollectionPolicies {
        bunny,
        fox,
        bunny_sampler: RecurrentSampler::new(seeds.action ^ sample_index.rotate_left(17)),
        fox_sampler: RecurrentSampler::new(
            seeds.action ^ 0x666f_785f_6163_746e ^ sample_index.rotate_left(29),
        ),
    }
}

/// Collect independent worlds under one unchanged behavior policy snapshot.
const fn curriculum_rollout_stage(target: CurriculumStage, lane: usize) -> CurriculumStage {
    // Survival's visible batch is one homogeneous environment contract. Its
    // separate teacher and retention gate preserve forage behavior.
    if matches!(target, CurriculumStage::Survival) {
        return target;
    }
    let Some(predecessor) = predecessor_stage(target) else {
        return target;
    };
    match lane % 10 {
        0 => CurriculumStage::Forage,
        1 | 2 => predecessor,
        _ => target,
    }
}

/// Retain foundation forage lanes after promotion while emphasizing the hard lesson.
const fn forage_rollout_difficulty(current: ForageDifficulty, lane: usize) -> ForageDifficulty {
    if matches!(current, ForageDifficulty::Expanded) && lane % 10 < 2 {
        ForageDifficulty::Foundation
    } else {
        current
    }
}

/// Apply the abundant lesson or the promoted retained scarcity mixture.
fn apply_competition_resource_curriculum(config: &mut SimulationConfig, scarce: bool, lane: usize) {
    let uses_foundation = !scarce || matches!(lane % 10, 3 | 4);
    if config.stage != CurriculumStage::Competition || !uses_foundation {
        return;
    }
    config.initial_food = COMPETITION_FOUNDATION_INITIAL_FOOD;
    config.max_food = COMPETITION_FOUNDATION_MAX_FOOD;
    config.well_capacity = COMPETITION_FOUNDATION_WELL_CAPACITY;
}

/// Return the annealed training-only forage nursery coefficient.
fn forage_nursery_beta(
    difficulty: ForageDifficulty,
    iteration: usize,
    total_iterations: usize,
) -> f32 {
    if difficulty == ForageDifficulty::Foundation || total_iterations == 0 {
        return 0.0;
    }
    let zero_iteration = total_iterations.saturating_mul(3) / 4;
    if zero_iteration == 0 || iteration >= zero_iteration {
        return 0.0;
    }
    let remaining_fraction = 1.0 - iteration as f32 / zero_iteration as f32;
    FORAGE_NURSERY_BETA_START * remaining_fraction
}

/// Return a bounded food potential from the nearest visible food ray.
fn forage_food_potential(observation: &LocalObservation) -> f32 {
    nearest_observed_ray(observation, PerceptKind::Food)
        .map_or(-1.0, |(_, distance)| -distance.clamp(0.0, 1.0))
}

/// Add temporary potential shaping to one forage collection transition.
fn forage_nursery_reward(
    task_reward: f32,
    observation: &LocalObservation,
    next_observation: &LocalObservation,
    status: EpisodeStatus,
    consumed_food: bool,
    gamma: f32,
    beta: f32,
) -> f32 {
    if beta <= 0.0 {
        return task_reward;
    }
    let current_potential = forage_food_potential(observation);
    let next_potential = if status == EpisodeStatus::Continuing && !consumed_food {
        forage_food_potential(next_observation)
    } else {
        0.0
    };
    beta.mul_add(
        gamma.mul_add(next_potential, -current_potential),
        task_reward,
    )
}

/// Generate deterministic actor-visible approach demonstrations from reset states.
fn forage_expert_samples(
    config: SimulationConfig,
    seed: u64,
    count: usize,
) -> Result<Vec<RecurrentBehaviorSample>, Box<dyn Error>> {
    let mut samples = Vec::with_capacity(count);
    for index in 0..count {
        let episode_seed = seed ^ (index as u64).rotate_left(17);
        let mut ecosystem = Ecosystem::new_rotated(config.clone(), episode_seed, index)?;
        let state = ecosystem.state();
        let (_, species, observation) = state
            .agents
            .first()
            .ok_or("forage expert world has no actor")?;
        let Some(bearing) = observed_ray_bearing(observation, PerceptKind::Food) else {
            return Err("forage expert reset must expose one visible bunny target".into());
        };
        if species != &Species::Bunny {
            return Err("forage expert reset must contain a bunny actor".into());
        }
        let forward = if bearing.abs() < 0.20 { 1.0 } else { -1.0 };
        let turn = (bearing / 0.35).clamp(-1.0, 1.0);
        samples.push(RecurrentBehaviorSample {
            observation: observation.to_vec(),
            action: vec![forward, turn, 0.0, 1.0],
        });
    }
    Ok(samples)
}

