/// Pooled same-policy sequences and lifetimes for one optimizer iteration.
#[derive(Debug, Default)]
struct CollectedBatch {
    /// All bunny trajectory chunks across environment lanes.
    bunny_sequences: Vec<RecurrentPpoSequence>,

    /// All fox trajectory chunks across environment lanes.
    fox_sequences: Vec<RecurrentPpoSequence>,

    /// Joint environment steps summed across lanes.
    joint_steps: u64,

    /// Per-episode bunny mean lifetimes.
    bunny_lifetimes: Vec<f32>,

    /// Per-episode fox mean lifetimes.
    fox_lifetimes: Vec<f32>,

    /// Per-episode bunny mean undiscounted returns.
    bunny_returns: Vec<f32>,

    /// Per-episode fox mean undiscounted returns.
    fox_returns: Vec<f32>,

    /// Exact nine-lane replay from this optimizer batch.
    #[cfg(feature = "render")]
    visual_trace: Option<SurvivalBatchTrace>,
}

impl CollectedBatch {
    /// Add one completed environment lane to the stable optimizer batch.
    fn push_lane(&mut self, lane: CollectedLane, algorithm: &RecurrentPpoConfig) {
        self.joint_steps = self
            .joint_steps
            .saturating_add(u64::from(lane.episode.joint_steps));
        self.bunny_lifetimes.push(mean_lifetime(
            &lane.episode,
            Species::Bunny,
            lane.config.time_step,
        ));
        self.bunny_returns
            .push(mean_episode_return(&lane.episode, Species::Bunny));
        if lane.config.fox_count > 0 {
            self.fox_lifetimes.push(mean_lifetime(
                &lane.episode,
                Species::Fox,
                lane.config.time_step,
            ));
            self.fox_returns
                .push(mean_episode_return(&lane.episode, Species::Fox));
        }
        self.bunny_sequences.extend(build_sequences(
            &lane.episode.trajectories,
            Species::Bunny,
            algorithm.gamma,
            algorithm.gae_lambda,
        ));
        self.fox_sequences.extend(build_sequences(
            &lane.episode.trajectories,
            Species::Fox,
            algorithm.gamma,
            algorithm.gae_lambda,
        ));
    }
}

