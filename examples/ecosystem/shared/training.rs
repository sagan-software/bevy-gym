/// Stateful forage promotion derived only from scheduled validation passes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct ForagePromotion {
    /// Current reset distribution.
    difficulty: ForageDifficulty,
    /// Consecutive foundation validations that met the promotion contract.
    consecutive_passes: u8,
}

impl Default for ForagePromotion {
    fn default() -> Self {
        Self {
            difficulty: ForageDifficulty::Foundation,
            consecutive_passes: 0,
        }
    }
}

impl ForagePromotion {
    /// Record one validation result and return whether promotion occurred.
    fn record(&mut self, summary: EvaluationSummary) -> bool {
        if self.difficulty == ForageDifficulty::Expanded {
            return false;
        }
        let passed = summary.bunny_food_fraction >= 0.80;
        self.consecutive_passes = if passed {
            self.consecutive_passes.saturating_add(1)
        } else {
            0
        };
        if self.consecutive_passes < 3 {
            return false;
        }
        self.difficulty = ForageDifficulty::Expanded;
        true
    }

    /// Return the current reset distribution.
    const fn difficulty(self) -> ForageDifficulty {
        self.difficulty
    }
}

/// Stateful competition promotion derived from scheduled validation passes.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
struct CompetitionPromotion {
    /// Whether scarce resource collection is active.
    scarce: bool,
    /// Consecutive validations that met the fair-access contract.
    consecutive_passes: u8,
}

impl CompetitionPromotion {
    /// Construct a promotion state for a predecessor transfer or continuation.
    const fn new(starts_scarce: bool) -> Self {
        Self {
            scarce: starts_scarce,
            consecutive_passes: 0,
        }
    }

    /// Record one validation result and return whether promotion occurred.
    fn record(&mut self, summary: EvaluationSummary) -> bool {
        if self.scarce {
            return false;
        }
        let passed = summary.bunny_resource_consumer_count >= 4
            && summary.bunny_index_lifetime_advantage_fraction <= 0.20
            && summary.contact_displacements > 0;
        self.consecutive_passes = if passed {
            self.consecutive_passes.saturating_add(1)
        } else {
            0
        };
        if self.consecutive_passes < COMPETITION_PROMOTION_PASSES {
            return false;
        }
        self.scarce = true;
        true
    }

    /// Return whether the scarce competition profile is active.
    const fn is_scarce(self) -> bool {
        self.scarce
    }
}

